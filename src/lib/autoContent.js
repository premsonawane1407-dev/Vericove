import { state, persist } from '../core.js';

const POLL_INTERVAL = 30 * 60 * 1000;
let inFlight = false;
const NIMH_VIDEO_SOURCE = 'https://www.nimh.nih.gov/get-involved/digital-shareables/shareable-resources-on-depression';
const approvedFallbacks = [
  ['lQhpetkwWnM', 'Depression Mental Health Minute', 'A short educational video from NIMH about depression.'],
  ['AQqG2oikEng', 'Teen Depression Study', 'An NIMH video about research into teen depression.'],
].map(([videoId, title, description]) => {
  const shared = {
    author: 'NIMH', time: 'Official video', community: 'Health Research',
    autoGenerated: true, sourceLabel: 'NIMH Digital Shareables', sourceUrl: NIMH_VIDEO_SOURCE,
    sourceNote: 'Video is embedded from YouTube and remains hosted by its original publisher.',
    embedProvider: 'youtube', videoId, comments: [], votes: 0, likes: 0, voted: false, saved: false,
  };
  const body = `${description} This educational resource is shared by NIMH.`;
  return { ...shared, id: `nimh-post-${videoId}`, tag: 'Education', title, body };
});

export function seedApprovedContent() {
  const known = new Set(state.posts.map(post => post.id));
  const additions = approvedFallbacks.filter(post => !known.has(post.id));
  if (!additions.length) return false;
  state.posts = [...additions, ...state.posts].slice(0, 300);
  persist();
  return true;
}

export async function refreshAutoContent() {
  if (inFlight) return;
  inFlight = true;
  try {
    const response = await fetch('/api/auto-content', { headers: { accept: 'application/json' } });
    if (!response.ok) return;
    const payload = await response.json();
    const known = new Set(state.posts.map(post => post.id));
    const additions = (Array.isArray(payload.items) ? payload.items : []).filter(post => post?.id && !known.has(post.id));
    if (!additions.length) return;
    state.posts = [...additions, ...state.posts].slice(0, 300);
    persist();
    document.dispatchEvent(new CustomEvent('content:auto-updated'));
  } catch {
    // The community remains usable while offline or while the source feed is down.
  } finally {
    inFlight = false;
  }
}

export function startAutoContent() {
  const obsolete = state.posts.filter(post => /^(?:nih|nimh)-reel-/.test(post.id || ''));
  if (obsolete.length) {
    state.posts = state.posts.filter(post => !/^(?:nih|nimh)-reel-/.test(post.id || ''));
    persist();
    document.dispatchEvent(new CustomEvent('content:auto-updated'));
  }
  void refreshAutoContent();
  window.setInterval(() => {
    if (document.visibilityState === 'visible') void refreshAutoContent();
  }, POLL_INTERVAL);
}
