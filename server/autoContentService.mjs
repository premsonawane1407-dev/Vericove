import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const FEED_URL = 'https://www.nih.gov/news-releases/feed.xml';
const CACHE_DIR = join(tmpdir(), 'vericove-auto-content');
const CACHE_FILE = join(CACHE_DIR, 'nih-releases.json');
const POLL_INTERVAL = 60 * 60 * 1000;
const LIMIT = 80;
let cache = { initialized: false, seen: [], items: [], checkedAt: null, lastError: null };
let refreshPromise;

function decodeEntities(value = '') {
  return value.replace(/&#(\d+);/g, (_, code) => String.fromCodePoint(Number(code)))
    .replace(/&#x([\da-f]+);/gi, (_, code) => String.fromCodePoint(parseInt(code, 16)))
    .replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&apos;|&#39;/g, "'")
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>');
}

function cleanText(value = '') {
  return decodeEntities(value.replace(/<!\[CDATA\[([\s\S]*?)\]\]>/g, '$1').replace(/<[^>]*>/g, ' '))
    .replace(/\s+/g, ' ').trim();
}

function extractItems(xml) {
  return [...xml.matchAll(/<item\b[^>]*>([\s\S]*?)<\/item>/gi)].map(([, item]) => {
    const field = name => item.match(new RegExp(`<${name}(?:\\s[^>]*)?>([\\s\\S]*?)<\\/${name}>`, 'i'))?.[1] || '';
    const title = cleanText(field('title'));
    const link = cleanText(field('link'));
    const description = cleanText(field('description'));
    const pubDate = cleanText(field('pubDate'));
    if (!title || !/^https:\/\/(?:www\.)?nih\.gov\//i.test(link)) return null;
    return { title: title.slice(0, 240), link, description: description.slice(0, 900), pubDate };
  }).filter(Boolean);
}

function makePair(release) {
  const id = createHash('sha256').update(release.link).digest('hex').slice(0, 18);
  const detail = release.description || 'Read the official release for the full context and details.';
  const summary = detail.length > 300 ? `${detail.slice(0, 297).trimEnd()}…` : detail;
  const common = {
    author: 'Vericove Research Desk', time: release.pubDate || 'Recently', community: 'Health Research',
    tag: 'Research', autoGenerated: true, sourceLabel: 'NIH News Release', sourceUrl: release.link,
    sourceNote: 'Summary based on an official NIH release. Read the source for context. Not medical advice.',
    comments: [], votes: 0, likes: 0, voted: false, saved: false,
  };
  return [
    { ...common, id: `nih-post-${id}`, title: release.title, body: summary },
    {
      ...common, id: `nih-reel-${id}`, type: 'reel', tag: 'Video', title: release.title,
      body: summary, autoReel: { summary, sourceUrl: release.link, sourceLabel: 'NIH News Release' },
    },
  ];
}

async function saveCache() {
  await mkdir(CACHE_DIR, { recursive: true });
  await writeFile(CACHE_FILE, JSON.stringify(cache), 'utf8');
}

async function loadCache() {
  try {
    const stored = JSON.parse(await readFile(CACHE_FILE, 'utf8'));
    if (Array.isArray(stored.items) && Array.isArray(stored.seen)) cache = { ...cache, ...stored };
  } catch { /* first launch */ }
}

async function refresh() {
  if (refreshPromise) return refreshPromise;
  refreshPromise = (async () => {
    try {
      const response = await fetch(FEED_URL, { headers: { accept: 'application/rss+xml, application/xml, text/xml' }, signal: AbortSignal.timeout(15000) });
      if (!response.ok) throw new Error(`NIH feed returned ${response.status}`);
      const releases = extractItems(await response.text());
      const fresh = releases.filter(item => !cache.seen.includes(item.link));
      // Don't dump the feed's entire archive into a new demo. Seed only its newest
      // release on first run; subsequent polls add releases as they appear.
      if (!cache.initialized) {
        cache.seen = releases.map(item => item.link);
        cache.initialized = true;
        if (releases[0]) cache.items.push(...makePair(releases[0]));
      } else if (fresh.length) {
        const latest = fresh[0];
        cache.seen.push(...fresh.map(item => item.link));
        cache.items.unshift(...makePair(latest));
        cache.items = cache.items.slice(0, LIMIT * 2);
      }
      cache.checkedAt = new Date().toISOString();
      cache.lastError = null;
      await saveCache();
    } catch (error) {
      cache.lastError = error?.message || 'Feed refresh failed';
      cache.checkedAt = new Date().toISOString();
    }
  })().finally(() => { refreshPromise = null; });
  return refreshPromise;
}

export function autoContentPlugin() {
  let timer;
  return {
    name: 'vericove-auto-content',
    configureServer(server) {
      void loadCache().then(refresh);
      timer = setInterval(() => void refresh(), POLL_INTERVAL);
      timer.unref?.();
      server.httpServer?.once('close', () => clearInterval(timer));
      server.middlewares.use('/api/auto-content', async (req, res) => {
        if (req.method !== 'GET') {
          res.statusCode = 405;
          res.setHeader('Allow', 'GET');
          res.end('Method not allowed');
          return;
        }
        await loadCache();
        if (!cache.checkedAt || Date.now() - new Date(cache.checkedAt).getTime() > POLL_INTERVAL) await refresh();
        res.setHeader('Content-Type', 'application/json; charset=utf-8');
        res.setHeader('Cache-Control', 'no-store');
        res.end(JSON.stringify({ items: cache.items, checkedAt: cache.checkedAt, source: 'NIH News Releases', error: cache.lastError }));
      });
    },
  };
}
